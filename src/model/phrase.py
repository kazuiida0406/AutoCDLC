from dataclasses import dataclass



@dataclass
class Phrase:
    """
    Rocksmith Phrase Model

    XML:
    <phrases>
        <phrase>
    """



    # ==========================================
    # ID
    # ==========================================

    id: int = 0



    # ==========================================
    # Name
    # ==========================================

    name: str = ""



    # ==========================================
    # Difficulty
    # ==========================================

    max_level_difficulty: int = 0



    # ==========================================
    # Solo
    # ==========================================

    solo: int = 0



    # ==========================================
    # Helper
    # ==========================================

    def __repr__(self):

        return (
            f"Phrase("
            f"id={self.id}, "
            f"name='{self.name}'"
            f")"
        )